/**
 * scaffold.ts — the files `hush init` SHIPS (PLAN §4; TOOL-MATRIX). Each
 * template encodes hush's doctrine: gitleaks pinned + an allowlist that stops
 * the `password = "password"` FP storm (S-12/P-03), a SOPS config with a
 * MANDATORY break-glass 2nd recipient (O-07/S-04), and the .gitignore/.env.example
 * dogfood fix (O-01/O-02). All writes are non-destructive: existing files are
 * left untouched and reported as "skipped".
 */
import { execFileSync } from "node:child_process";
import {
  appendFileSync,
  chmodSync,
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { homedir } from "node:os";
import { dirname, isAbsolute, join } from "node:path";
import { generateEnvExample } from "./env-example.js";
import { GITLEAKS_BASELINE_TOML, GITLEAKS_PINNED_VERSION } from "../scanners/gitleaks.js";
import { TRUFFLEHOG_PINNED_VERSION } from "../scanners/trufflehog.js";

export interface ScaffoldStep {
  readonly file: string;
  readonly status: "written" | "skipped-exists" | "skipped-unavailable";
  readonly note?: string;
}

function writeIfAbsent(repo: string, rel: string, body: string): ScaffoldStep {
  const full = join(repo, rel);
  if (existsSync(full)) return { file: rel, status: "skipped-exists" };
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, body, "utf8");
  return { file: rel, status: "written" };
}

const PRECOMMIT = `# .pre-commit-config.yaml — generated by \`hush init --scanner\`.
# Prevention layer: gitleaks blocks secrets BEFORE they enter history (the only
# place prevention is possible — O-03). Pinned (P-05): never \`curl | sh\` latest.
repos:
  - repo: https://github.com/gitleaks/gitleaks
    rev: v${GITLEAKS_PINNED_VERSION}
    hooks:
      - id: gitleaks
`;

function ciWorkflow(): string {
  return `# .github/workflows/secret-scan.yml — generated by \`hush init --scanner\`.
# Detection-with-proof layer (O-03): gitleaks history + trufflehog --only-verified.
# Pinned + offline-capable ($0). Scans git HISTORY, not just the working tree.
name: secret-scan
on: [push, pull_request]
jobs:
  scan:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
        with:
          fetch-depth: 0 # full history (O-03 sub-stance)
      - name: gitleaks (pinned ${GITLEAKS_PINNED_VERSION})
        uses: gitleaks/gitleaks-action@v2
      - name: trufflehog (pinned ${TRUFFLEHOG_PINNED_VERSION}, verified only)
        uses: trufflesecurity/trufflehog@main
        with:
          extra_args: --only-verified
`;
}

/** Build a .sops.yaml with a break-glass 2nd recipient (O-07/S-04). */
function sopsYaml(ageRecipient: string): string {
  return `# .sops.yaml — generated by \`hush init --sops\`.
# MANDATORY: ≥2 recipients so a single-provider regression (#1695, P-10) can't
# lock you out — a break-glass age key alongside your primary (O-07/S-04).
creation_rules:
  - path_regex: .*\\.enc\\.(yaml|json|env)$
    age: >-
      ${ageRecipient},
      age1BREAKGLASSREPLACEMEREPLACEMEREPLACEMEREPLACEMExxxxxxx
# ^ replace the 2nd recipient with a real offline break-glass age key:
#   age-keygen -o breakglass.txt   (store the private key OFFLINE, not in git)
`;
}

/**
 * The age keys file sops reads by default: $SOPS_AGE_KEY_FILE, else
 * <config dir>/sops/age/keys.txt. The config dir is $XDG_CONFIG_HOME when set,
 * else ~/Library/Application Support on macOS, ~/.config on Linux and
 * %AppData% on Windows (TOOL-MATRIX, "SOPS + age (decrypt)").
 */
export function sopsAgeKeyFile(
  env: NodeJS.ProcessEnv = process.env,
  platform: NodeJS.Platform = process.platform,
  home: string = homedir(),
): string {
  if (env.SOPS_AGE_KEY_FILE) return env.SOPS_AGE_KEY_FILE;
  let base = env.XDG_CONFIG_HOME || join(home, ".config");
  if (platform === "darwin") {
    base = env.XDG_CONFIG_HOME || join(home, "Library", "Application Support");
  }
  if (platform === "win32") base = env.APPDATA || join(home, "AppData", "Roaming");
  return join(base, "sops", "age", "keys.txt");
}

/**
 * Add a key to the keys file at mode 600. An existing file is appended to,
 * never overwritten. An encrypted keys file is refused: plain text after it
 * would break it.
 */
function saveAgeKey(file: string, keyText: string): "created" | "appended" {
  if (!existsSync(file)) {
    mkdirSync(dirname(file), { recursive: true, mode: 0o700 });
    writeFileSync(file, keyText, { encoding: "utf8", mode: 0o600, flag: "wx" });
    return "created";
  }
  const prev = readFileSync(file);
  const head = prev.subarray(0, 14).toString("latin1");
  if (head.startsWith("age-encryption") || head.startsWith("-----BEGIN AGE")) {
    throw new Error("it is an encrypted keys file, and hush will not append plain text to it");
  }
  const sep = prev.length > 0 && prev[prev.length - 1] !== 0x0a ? "\n" : "";
  appendFileSync(file, sep + keyText, "utf8");
  chmodSync(file, 0o600);
  return "appended";
}

const PLACEHOLDER_RECIPIENT = "age1REPLACEMEWITHYOURPRIMARYAGEPUBLICKEYxxxxxxxxxxxxxx";

/**
 * Self-generate the primary age key (SEC-1, no provider account). Its public
 * key goes into .sops.yaml only once its private key is saved where sops looks,
 * since nobody could decrypt for an unsaved key. The private key is never printed.
 */
function primaryAgeKey(): { recipient: string; note: string } {
  const keyFile = sopsAgeKeyFile();
  if (!isAbsolute(keyFile)) {
    return {
      recipient: PLACEHOLDER_RECIPIENT,
      note: `no age key made: the keys file path (${keyFile}) is not absolute, so a key could land in the repo. Replace the recipient`,
    };
  }
  let out: string;
  try {
    out = execFileSync("age-keygen", [], { encoding: "utf8" });
  } catch {
    return {
      recipient: PLACEHOLDER_RECIPIENT,
      note: `age-keygen not installed. Run \`age-keygen -o ${keyFile}\`, then replace the recipient`,
    };
  }
  const recipient = /# public key: (age1[0-9a-z]+)/.exec(out)?.[1];
  if (!recipient || !/^AGE-SECRET-KEY-1/m.test(out)) {
    return {
      recipient: PLACEHOLDER_RECIPIENT,
      note: "age-keygen output not recognised, so no key was saved. Replace the recipient with your own",
    };
  }
  try {
    const how = saveAgeKey(keyFile, out);
    return {
      recipient,
      note: `age key generated. Private key ${how === "created" ? "saved to" : "appended to"} ${keyFile} (mode 600), where sops looks for it. Only its public key is in .sops.yaml`,
    };
  } catch (err) {
    return {
      recipient: PLACEHOLDER_RECIPIENT,
      note: `age key not saved to ${keyFile}: ${err instanceof Error ? err.message : String(err)}. Replace the recipient with a key you keep`,
    };
  }
}

function scaffoldSops(repo: string): ScaffoldStep[] {
  // An existing .sops.yaml is left alone, so no key is generated for it.
  if (existsSync(join(repo, ".sops.yaml"))) {
    return [{ file: ".sops.yaml", status: "skipped-exists" }];
  }
  const { recipient, note } = primaryAgeKey();
  const step = writeIfAbsent(repo, ".sops.yaml", sopsYaml(recipient));
  return [{ ...step, note }];
}

export interface InitFlags {
  readonly scanner?: boolean;
  readonly sops?: boolean;
  readonly gitignore?: boolean;
  readonly envExample?: boolean;
}

/** Run the requested scaffolders (none specified = all). Returns per-file steps. */
export function scaffold(repo: string, flags: InitFlags): ScaffoldStep[] {
  const all = !flags.scanner && !flags.sops && !flags.gitignore && !flags.envExample;
  const steps: ScaffoldStep[] = [];

  if (all || flags.scanner) {
    steps.push(writeIfAbsent(repo, ".gitleaks.toml", GITLEAKS_BASELINE_TOML));
    steps.push(writeIfAbsent(repo, ".pre-commit-config.yaml", PRECOMMIT));
    steps.push(writeIfAbsent(repo, ".github/workflows/secret-scan.yml", ciWorkflow()));
  }
  if (all || flags.sops) {
    steps.push(...scaffoldSops(repo));
  }
  if (all || flags.gitignore) {
    const giPath = join(repo, ".gitignore");
    if (existsSync(giPath)) {
      steps.push({
        file: ".gitignore",
        status: "skipped-exists",
        note: "exists — verify it has `.env*` and `!.env.example` (O-01/P-01); not overwritten",
      });
    } else {
      steps.push(
        writeIfAbsent(
          repo,
          ".gitignore",
          "# Secrets — ignore every .env variant, keep the schema tracked (O-01/P-01)\n.env*\n!.env.example\nnode_modules/\ndist/\n",
        ),
      );
    }
  }
  if (all || flags.envExample) {
    const { body } = generateEnvExample(repo);
    steps.push(writeIfAbsent(repo, ".env.example", body));
  }

  return steps;
}
