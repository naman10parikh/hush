/**
 * env-example.ts — GENERATE .env.example from the repo's real var schema (S-14).
 *
 * The lazy path (`cp ../other/.env.example .`) drags a stale superset; hush
 * instead discovers the vars the code ACTUALLY reads and emits placeholders
 * only (never a real value, O-02). This is the engine behind `hush env-example`.
 */
import { execFileSync } from "node:child_process";
import { readFileSync, statSync } from "node:fs";
import { join } from "node:path";

// Patterns the code uses to read env vars (Node, Vite, Python os.environ).
// NOTE: the broad shell `$VAR` pattern is deliberately OMITTED — in shell files
// `$UPPERCASE` matches LOCAL variables too, producing a stale superset, which is
// the exact anti-pattern S-14 warns against. We detect only explicit env reads.
const ENV_REFS: readonly RegExp[] = [
  /process\.env\.([A-Z][A-Z0-9_]*)/g,
  /process\.env\[["']([A-Z][A-Z0-9_]*)["']\]/g,
  /import\.meta\.env\.([A-Z][A-Z0-9_]*)/g,
  /os\.environ(?:\.get)?\(["']([A-Z][A-Z0-9_]*)["']\)/g,
];

const SOURCE_FILE = /\.(ts|tsx|js|jsx|mjs|cjs|py)$/;
const MAX_FILE_BYTES = 1_000_000;

// Vars that are environment noise, not secrets/config the repo owns.
const IGNORE = new Set([
  "PATH",
  "HOME",
  "PWD",
  "SHELL",
  "USER",
  "LANG",
  "TERM",
  "NODE_ENV",
  "CI",
  "TMPDIR",
  "OLDPWD",
]);

/** A placeholder + comment per known var family (best-effort, generic otherwise). */
function placeholderFor(name: string): { value: string; comment: string } {
  if (/ANTHROPIC|CLAUDE/.test(name)) return { value: "sk-ant-...", comment: "Anthropic API key" };
  if (/OPENAI/.test(name)) return { value: "sk-...", comment: "OpenAI API key" };
  if (/GITHUB/.test(name)) return { value: "ghp_...", comment: "GitHub token" };
  if (/AWS_ACCESS_KEY_ID/.test(name)) return { value: "AKIA...", comment: "AWS access key id" };
  if (/AWS_SECRET/.test(name)) return { value: "...", comment: "AWS secret access key" };
  if (/E2B/.test(name)) return { value: "e2b_...", comment: "E2B sandbox key" };
  if (/AGE_KEY|SOPS/.test(name)) return { value: "/path/to/keys.txt", comment: "SOPS/age key file path" };
  if (/ADDR|URL|HOST/.test(name)) return { value: "https://...", comment: "endpoint URL" };
  if (/TOKEN|SECRET|KEY|PASSWORD/.test(name)) return { value: "...", comment: "secret — set in your gitignored .env" };
  return { value: "...", comment: "config value" };
}

function git(args: readonly string[], cwd: string): string {
  return execFileSync("git", args, { cwd, encoding: "utf8", maxBuffer: 32 * 1024 * 1024 });
}

/** Discover the env vars referenced anywhere in the repo's tracked source. */
export function discoverEnvVars(repoPath: string): string[] {
  let files: string[] = [];
  try {
    files = git(["ls-files"], repoPath).split("\n").map((f) => f.trim()).filter(Boolean);
  } catch {
    files = [];
  }
  const found = new Set<string>();
  for (const rel of files) {
    if (!SOURCE_FILE.test(rel)) continue;
    const full = join(repoPath, rel);
    try {
      if (statSync(full).size > MAX_FILE_BYTES) continue;
      const text = readFileSync(full, "utf8");
      for (const re of ENV_REFS) {
        re.lastIndex = 0;
        let m: RegExpExecArray | null;
        while ((m = re.exec(text)) !== null) {
          const name = m[1];
          if (name && !IGNORE.has(name) && name.length >= 3) found.add(name);
        }
      }
    } catch {
      // Intentionally silent: unreadable file is not a var source.
    }
  }
  return [...found].sort();
}

/** Render a generated .env.example body for `repoPath`. */
export function generateEnvExample(repoPath: string): { body: string; vars: readonly string[] } {
  const vars = discoverEnvVars(repoPath);
  const lines = [
    "# Generated by `hush env-example` from this repo's real var schema (S-14).",
    "# Placeholders only — never commit real values. `.env` is gitignored; this schema is tracked.",
    "",
  ];
  if (vars.length === 0) {
    lines.push("# (no environment variables referenced in tracked source)");
  }
  for (const name of vars) {
    const { value, comment } = placeholderFor(name);
    lines.push(`# ${comment}`);
    lines.push(`${name}=${value}`);
    lines.push("");
  }
  return { body: lines.join("\n").trimEnd() + "\n", vars };
}
