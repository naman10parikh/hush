/**
 * gitleaks.ts — wrapper around the gitleaks binary (the preferred prevent/catch
 * scanner, O-03). Pinned to 8.30.1 (brain TOOL-MATRIX; pin + checksum in CI per
 * P-05). DEGRADES GRACEFULLY: if gitleaks is not installed, returns
 * `{ available:false }` so the built-in scanner still satisfies the bar — never
 * crashes (PLAN §9 chaos: no-binary case).
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { redact } from "../lib/redact.js";
import type { Finding } from "./builtin.js";

export const GITLEAKS_PINNED_VERSION = "8.30.1";

/** hush's baseline: what `hush init --scanner` writes, and what a scan uses when a repo has no config. */
export const GITLEAKS_BASELINE_TOML = `# .gitleaks.toml — generated by \`hush init --scanner\`.
# EXTEND the upstream ruleset (do not replace it) — brain O-03/S-12/#741.
[extend]
useDefault = true

# Allowlist: stop the \`password = "password"\` FP storm (#1302, S-12/P-03) while
# keeping entropy gating so real low-entropy literals don't slip through.
[allowlist]
description = "hush baseline allowlist"
regexes = [
  '''password\\s*=\\s*["']?password["']?''',
  '''(?i)changeme|example|dummy|placeholder''',
  '''(?i)^["']?(password|changeme|secret|admin|root)["']?$''',
]
paths = [
  '''(.*?)\\.example$''',
  '''(.*?)\\.sample$''',
  '''(.*?)\\.template$''',
  '''fixtures?/''',
  '''testdata/''',
]
`;

/**
 * True when gitleaks would find no config of its own (no `<path>/.gitleaks.toml`, no GITLEAKS_CONFIG or
 * GITLEAKS_CONFIG_TOML). Then the scan passes hush's baseline with -c, so the default rules alone do not
 * flag decoys such as `password = "password"` (S-12/P-03). A repo's own config always wins.
 */
export function baselineNeeded(path: string, env: NodeJS.ProcessEnv = process.env): boolean {
  return !env.GITLEAKS_CONFIG && !env.GITLEAKS_CONFIG_TOML && !existsSync(join(path, ".gitleaks.toml"));
}

export interface GitleaksResult {
  readonly available: boolean;
  readonly findings: readonly Finding[];
  readonly note?: string;
}

function which(bin: string): boolean {
  try {
    execFileSync(process.platform === "win32" ? "where" : "which", [bin], {
      stdio: "ignore",
    });
    return true;
  } catch {
    return false;
  }
}

interface GitleaksRawFinding {
  readonly RuleID?: string;
  readonly File?: string;
  readonly Match?: string;
  readonly Secret?: string;
}

/**
 * Run gitleaks over `path`. `mode` = "detect" (history) or "protect" (staged).
 * Returns findings with secrets REDACTED (gitleaks emits raw secrets in JSON —
 * we strip them before they touch our output, O-09).
 */
export function gitleaksScan(
  path: string,
  mode: "detect" | "protect",
): GitleaksResult {
  if (!which("gitleaks")) {
    return {
      available: false,
      findings: [],
      note: `gitleaks not installed (pin ${GITLEAKS_PINNED_VERSION}); built-in scanner used instead`,
    };
  }
  let baselineDir: string | undefined;
  try {
    // gitleaks exits 1 when findings exist — capture stdout regardless.
    const args =
      mode === "protect"
        ? ["protect", "--staged", "--report-format", "json", "--report-path", "-", "-s", path]
        : ["detect", "--report-format", "json", "--report-path", "-", "-s", path];
    if (baselineNeeded(path)) {
      baselineDir = mkdtempSync(join(tmpdir(), "hush-gitleaks-"));
      const config = join(baselineDir, "gitleaks.toml");
      writeFileSync(config, GITLEAKS_BASELINE_TOML, "utf8");
      args.push("-c", config);
    }
    let stdout = "";
    try {
      stdout = execFileSync("gitleaks", args, { encoding: "utf8" });
    } catch (err: unknown) {
      // gitleaks exit 1 = findings; its JSON is still on stdout.
      const e = err as { stdout?: string };
      stdout = typeof e.stdout === "string" ? e.stdout : "";
    }
    const raw = stdout.trim() ? (JSON.parse(stdout) as GitleaksRawFinding[]) : [];
    const findings: Finding[] = raw.map((r) => ({
      rule: r.RuleID ?? "gitleaks-finding",
      file: r.File ?? "<unknown>",
      redacted_snippet: redact(r.Match ?? r.Secret ?? "").slice(0, 200),
      source: mode === "protect" ? "working-tree" : "history",
    }));
    return { available: true, findings };
  } catch (err) {
    return {
      available: true,
      findings: [],
      note: `gitleaks run failed: ${err instanceof Error ? err.message : String(err)}`,
    };
  } finally {
    if (baselineDir) rmSync(baselineDir, { recursive: true, force: true });
  }
}
